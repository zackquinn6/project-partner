#!/usr/bin/env node
/**
 * Phase 4: generate Toolio's vocabulary-link migration.
 *
 *   node scripts/vocab-merge/build-toolio-load.mjs --archive <export folder> --out <toolio migration file> [--dry-run]
 *
 * Inputs: the export folder (fully decided crosswalk, toolio-1-catalog, pp-snapshot taken after
 * Project Partner's phase 3 load) and scripts/vocab-merge/sql/toolio-phase4-schema.sql.
 * Every Toolio inventory core and project must map to exactly one key present in the snapshot,
 * with groupings on categories and guided projects on families; otherwise nothing is written.
 *
 * Env: VOCAB_MERGE_ARCHIVE_DIR.
 */
import { readFileSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';
import { fileURLToPath } from 'node:url';
import { archiveDir, parseArgs, readCsv, readJson, readPayload, tableRows } from './lib.mjs';

const SQL_DIR = fileURLToPath(new URL('./sql/', import.meta.url));
const args = parseArgs();
if (!args.out && !args.dryRun) throw new Error('Pass --out <toolio migration file>');
const dir = archiveDir(args.archive);
const crosswalk = readCsv(join(dir, 'vocab-crosswalk.csv'));
const snapshot = readPayload(dir, 'pp-snapshot');
const inventory = tableRows(readPayload(dir, 'toolio-1-catalog'), 'inventory_items');
const toolioProjects = readJson(join(dir, 'extract', 'toolio_projects.json'));

const problems = [];
const snapshotEntity = new Map(snapshot.terms.map((t) => [t.public_key, t.entity]));

const coreLinks = new Map();
const projectLinks = new Map(); // id -> { key, kind }
for (const row of crosswalk) {
  if (!row.toolio_id) continue;
  if (!row.decision) problems.push(`Crosswalk row for ${row.toolio_name} has no decision`);
  const key = row.canonical_key;
  if (row.entity === 'tool' || row.entity === 'material') {
    if (coreLinks.has(row.toolio_id) && coreLinks.get(row.toolio_id) !== key) {
      problems.push(`Toolio core ${row.toolio_name} maps to ${coreLinks.get(row.toolio_id)} and ${key}`);
    }
    coreLinks.set(row.toolio_id, key);
    if (!['tool', 'material'].includes(snapshotEntity.get(key))) problems.push(`Core ${row.toolio_name}: ${key} is not a tool or material in the snapshot`);
  } else if (row.entity === 'project' || row.entity === 'category') {
    const kind = row.entity === 'project' ? 'family' : 'category';
    const expectedEntity = row.entity === 'project' ? 'project' : 'category';
    if (projectLinks.has(row.toolio_id) && projectLinks.get(row.toolio_id).key !== key) {
      problems.push(`Toolio project ${row.toolio_name} maps to ${projectLinks.get(row.toolio_id).key} and ${key}`);
    }
    projectLinks.set(row.toolio_id, { key, kind });
    if (snapshotEntity.get(key) !== expectedEntity) problems.push(`Project ${row.toolio_name}: ${key} is not a ${expectedEntity} in the snapshot`);
  }
}

const cores = inventory.filter((i) => i.parent_inventory_item_id === null);
for (const core of cores) if (!coreLinks.has(core.id)) problems.push(`Toolio core ${core.name} (${core.sku}) has no link`);
for (const id of coreLinks.keys()) if (!cores.some((c) => c.id === id)) problems.push(`Crosswalk core ${id} is not a Toolio core in this export`);
for (const project of toolioProjects) {
  const link = projectLinks.get(project.id);
  if (!link) problems.push(`Toolio project ${project.slug} has no link`);
  else if ((link.kind === 'category') !== project.is_grouping) problems.push(`Toolio project ${project.slug}: grouping and link kind disagree`);
}

if (problems.length) {
  console.error(`${problems.length} problems:\n  - ${[...new Set(problems)].join('\n  - ')}`);
  process.exit(1);
}

const termCounts = {};
for (const t of snapshot.terms) termCounts[t.entity] = (termCounts[t.entity] ?? 0) + 1;
const summary = {
  snapshot_as_of_seq: snapshot.as_of_seq,
  snapshot_terms: termCounts,
  open_removal_requests: (snapshot.removal_requests ?? []).length,
  core_links: coreLinks.size,
  project_links: [...projectLinks.values()].filter((l) => l.kind === 'family').length,
  grouping_links: [...projectLinks.values()].filter((l) => l.kind === 'category').length,
};
console.log(JSON.stringify(summary, null, 2));
if (args.dryRun) process.exit(0);

const q = (v) => `'${String(v).replace(/'/g, "''")}'`;
const snapshotJson = JSON.stringify({ as_of_seq: snapshot.as_of_seq, terms: snapshot.terms, removal_requests: snapshot.removal_requests });
const tag = '$pp_snapshot$';
if (snapshotJson.includes(tag)) throw new Error(`Snapshot contains ${tag}`);

const load = `
-- ===========================================================================
-- Part 3: load (generated by project-partner/scripts/vocab-merge/build-toolio-load.mjs)
-- ===========================================================================

DO $load$
BEGIN
  PERFORM public.pp_vocab_apply_snapshot(${tag}${snapshotJson}${tag}::jsonb);
END
$load$;

CREATE TEMP TABLE _pv_core_links (id uuid PRIMARY KEY, key text NOT NULL) ON COMMIT DROP;
INSERT INTO _pv_core_links VALUES
${[...coreLinks].map(([id, key]) => `  (${q(id)}, ${q(key)})`).join(',\n')};
CREATE TEMP TABLE _pv_project_links (id uuid PRIMARY KEY, key text NOT NULL, kind text NOT NULL) ON COMMIT DROP;
INSERT INTO _pv_project_links VALUES
${[...projectLinks].map(([id, l]) => `  (${q(id)}, ${q(l.key)}, ${q(l.kind)})`).join(',\n')};

UPDATE public.inventory_items i SET pp_vocab_key = l.key FROM _pv_core_links l WHERE i.id = l.id;
UPDATE public.projects p SET pp_vocab_key = l.key FROM _pv_project_links l WHERE p.id = l.id;

-- Accounting: any failure rolls the whole migration back.
DO $check$
DECLARE
  v_count bigint;
  v_detail text;
BEGIN
  SELECT string_agg(name || ' (' || sku || ')', ', ') INTO v_detail
  FROM public.inventory_items WHERE parent_inventory_item_id IS NULL AND pp_vocab_key IS NULL;
  IF v_detail IS NOT NULL THEN RAISE EXCEPTION 'vocab link: inventory cores without a link: %', v_detail; END IF;
  SELECT string_agg(slug, ', ') INTO v_detail FROM public.projects WHERE pp_vocab_key IS NULL;
  IF v_detail IS NOT NULL THEN RAISE EXCEPTION 'vocab link: projects without a link: %', v_detail; END IF;
  SELECT count(*) INTO v_count FROM public.inventory_items i JOIN _pv_core_links l ON l.id = i.id;
  IF v_count <> ${coreLinks.size} THEN RAISE EXCEPTION 'vocab link: % cores matched, expected ${coreLinks.size}', v_count; END IF;
  SELECT count(*) INTO v_count FROM public.projects p JOIN _pv_project_links l ON l.id = p.id;
  IF v_count <> ${projectLinks.size} THEN RAISE EXCEPTION 'vocab link: % projects matched, expected ${projectLinks.size}', v_count; END IF;
  SELECT string_agg(p.slug, ', ') INTO v_detail
  FROM public.projects p JOIN _pv_project_links l ON l.id = p.id JOIN public.pp_vocab_projects v ON v.public_key = p.pp_vocab_key
  WHERE v.kind <> l.kind;
  IF v_detail IS NOT NULL THEN RAISE EXCEPTION 'vocab link: projects linked to the wrong kind: %', v_detail; END IF;
  SELECT count(*) INTO v_count FROM public.pp_vocab_terms;
  IF v_count <> ${(termCounts.tool ?? 0) + (termCounts.material ?? 0)} THEN RAISE EXCEPTION 'vocab link: % mirrored tools and materials', v_count; END IF;
  SELECT count(*) INTO v_count FROM public.pp_vocab_projects;
  IF v_count <> ${(termCounts.project ?? 0) + (termCounts.category ?? 0)} THEN RAISE EXCEPTION 'vocab link: % mirrored projects and categories', v_count; END IF;
  SELECT last_seq INTO v_count FROM public.pp_vocab_sync_state WHERE id;
  IF v_count <> ${snapshot.as_of_seq} THEN RAISE EXCEPTION 'vocab link: sync cursor % , expected ${snapshot.as_of_seq}', v_count; END IF;
END
$check$;
`;

const migration = [
  '-- Toolio: link to the Project Partner vocabulary (phase 4, one migration).',
  '-- Generated by project-partner/scripts/vocab-merge/build-toolio-load.mjs; do not edit by hand.',
  `-- Export folder: ${args.archive}. Snapshot as of Project Partner change ${snapshot.as_of_seq}.`,
  `-- Links ${coreLinks.size} inventory cores and ${projectLinks.size} projects. Apply in one run; any failed check rolls everything back.`,
  '',
  'BEGIN;',
  '',
  readFileSync(join(SQL_DIR, 'toolio-phase4-schema.sql'), 'utf8'),
  load,
  'COMMIT;',
  '',
].join('\n');
writeFileSync(args.out, migration);
console.log(`Wrote ${args.out}`);
